package dev.cxtrends.brief;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.stereotype.Component;

import dev.cxtrends.CxProperties;
import tools.jackson.databind.ObjectMapper;
import tools.jackson.databind.SerializationFeature;

/** Part 3b: computes the facts, writes them, then writes the brief. */
@Component
public class BriefCommand {

    private static final Logger log = LoggerFactory.getLogger(BriefCommand.class);

    private final BriefFactsBuilder facts;
    private final BriefWriter writer;
    private final ObjectMapper json;
    private final CxProperties props;

    public BriefCommand(BriefFactsBuilder facts, BriefWriter writer, ObjectMapper json, CxProperties props) {
        this.facts = facts;
        this.writer = writer;
        this.json = json;
        this.props = props;
    }

    public void run() {
        BriefFacts f = facts.build();
        String factsJson = json.writer().with(SerializationFeature.INDENT_OUTPUT).writeValueAsString(f);
        write(props.outputDir().resolve("brief_facts.json"), factsJson);

        BriefWriter.Result brief = writer.write(f, factsJson);
        write(props.outputDir().resolve("cx_brief.md"), brief.markdown()
                + "\n\n---\n_Generated by the pipeline from `output/brief_facts.json`. Text: " + brief.generator() + "._\n");
        log.info("brief: {}", brief.generator());
    }

    private static void write(Path file, String content) {
        try {
            Files.createDirectories(file.toAbsolutePath().getParent());
            Files.writeString(file, content);
        } catch (IOException e) {
            throw new UncheckedIOException("write " + file, e);
        }
        log.info("wrote {}", file);
    }
}
