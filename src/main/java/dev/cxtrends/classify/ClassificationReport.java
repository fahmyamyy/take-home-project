package dev.cxtrends.classify;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.Map;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

import dev.cxtrends.CxProperties;

/**
 * Writes output/classification_report.md: how good the model is against the
 * human review, and where our topic and the agent's category disagree.
 *
 * <p>Every figure comes from SQL over the ticket_topics view, so the report is
 * regenerated, never hand-edited.
 */
@Component
public class ClassificationReport {

    private static final Logger log = LoggerFactory.getLogger(ClassificationReport.class);

    /** A ticket whose note is a real complaint but which the agent filed as Others › Unclassified. */
    private static final String DUMPED = "(subcategory = 'Unclassified' AND topic_category <> 'Others')";
    private static final String DISAGREE = "(category <> topic_category OR subcategory <> topic_subcategory)";

    private final JdbcTemplate jdbc;
    private final Path file;

    public ClassificationReport(JdbcTemplate jdbc, CxProperties props) {
        this.jdbc = jdbc;
        this.file = props.outputDir().resolve("classification_report.md");
    }

    public void write() {
        StringBuilder md = new StringBuilder();
        md.append("# Note classification vs agent category\n\n")
                .append("_Generated by `classify`; do not edit by hand._\n\n");
        summary(md);
        modelQuality(md);
        confusion(md);
        whereItHappens(md);
        impact(md);
        limitations(md);
        try {
            Files.createDirectories(file.toAbsolutePath().getParent());
            Files.writeString(file, md);
        } catch (IOException e) {
            throw new UncheckedIOException("write " + file, e);
        }
        log.info("wrote {}", file);
    }

    private void summary(StringBuilder md) {
        Map<String, Object> s = jdbc.queryForMap("""
                SELECT COUNT(*) AS tickets,
                       SUM(%1$s) AS disagree,
                       SUM(category <> topic_category) AS disagree_category,
                       SUM(%2$s) AS dumped,
                       SUM(%1$s AND NOT %2$s) AS other_disagreements,
                       SUM(subcategory = 'Unclassified') AS unclassified
                FROM ticket_topics
                """.formatted(DISAGREE, DUMPED));
        long tickets = num(s.get("tickets"));
        long unclassified = num(s.get("unclassified"));
        long dumped = num(s.get("dumped"));
        Map<String, Object> m = modelCounts();
        md.append("## Summary\n\n")
                .append("- **Our topic and the agent's label disagree on %s of %s tickets (%s)** "
                        .formatted(fmt(num(s.get("disagree"))), fmt(tickets), pct(num(s.get("disagree")), tickets)))
                .append("at subcategory level (%s at category level).\n".formatted(fmt(num(s.get("disagree_category")))))
                .append("- **%s of those are one pattern:** a specific complaint filed as *Others › Unclassified*. "
                        .formatted(fmt(dumped)))
                .append("%s of the %s Unclassified tickets (%s) describe a concrete problem — no signal, ".formatted(
                        fmt(dumped), fmt(unclassified), pct(dumped, unclassified)))
                .append("a package charged but not activated, and so on.\n")
                .append("- Disagreements of any other kind: **%s**. When an agent picks a specific category, it "
                        .formatted(fmt(num(s.get("other_disagreements")))))
                .append("matches the note.\n")
                .append("- The habit is uniform (≈15% across every channel, region, priority and topic — see below), ")
                .append("so agent-labelled volumes **miss about 15% of every real topic** (our counts are ~18% higher) ")
                .append("while keeping the shape of its trend. *Others* looks \"large\" mostly because of it.\n")
                .append("- The local model (`qwen2.5:3b`) agreed with the human review on **%s of %s** distinct texts "
                        .formatted(m.get("agree_texts"), m.get("texts")))
                .append("(%s of tickets). Final topics use the review.\n\n".formatted(
                        pct(num(m.get("agree_tickets")), num(m.get("tickets")))));
    }

    private Map<String, Object> modelCounts() {
        return jdbc.queryForMap("""
                SELECT COUNT(DISTINCT nt.base_text) AS texts,
                       COUNT(DISTINCT CASE WHEN nt.llm_category = nt.topic_category
                                            AND nt.llm_subcategory = nt.topic_subcategory THEN nt.base_text END) AS agree_texts,
                       COUNT(*) AS tickets,
                       SUM(nt.llm_category = nt.topic_category AND nt.llm_subcategory = nt.topic_subcategory) AS agree_tickets
                FROM note_topics nt
                JOIN ticket_notes n USING (base_text)
                """);
    }

    private void modelQuality(StringBuilder md) {
        md.append("## 1. How good is the model?\n\n")
                .append("Notes reduce to 91 distinct complaint texts once repeat-contact prefixes ")
                .append("(\"follow up dari laporan kemarin, …\") are removed. Each was classified once by `qwen2.5:3b` ")
                .append("and, separately, reviewed by a person (`review/topic_review.csv`). Where they differ:\n\n");
        List<Map<String, Object>> rows = jdbc.queryForList("""
                SELECT nt.base_text, nt.llm_category || ' › ' || nt.llm_subcategory AS model,
                       nt.topic_category || ' › ' || nt.topic_subcategory AS reviewed, COUNT(*) AS tickets
                FROM note_topics nt JOIN ticket_notes n USING (base_text)
                WHERE nt.llm_category <> nt.topic_category OR nt.llm_subcategory <> nt.topic_subcategory
                GROUP BY nt.base_text ORDER BY tickets DESC
                """);
        table(md, List.of("Note text", "Model said", "Review", "Tickets"), rows.stream()
                .map(r -> List.of(r.get("base_text").toString(), r.get("model").toString(), r.get("reviewed").toString(),
                        fmt(num(r.get("tickets")))))
                .toList());
        md.append("\nThe errors are near-misses between neighbouring topics (charge vs activation, top-up vs balance), ")
                .append("plus vague notes the model over-interprets. A prompt that makes the model restate the problem ")
                .append("before choosing a label lifted agreement from 71 to 81 of 91 texts; the remaining errors are why ")
                .append("a human review stays in the loop.\n\n");
    }

    private void confusion(StringBuilder md) {
        md.append("## 2. Agent category (rows) vs our topic (columns), tickets\n\n");
        List<String> categories = jdbc.queryForList(
                "SELECT DISTINCT category FROM tickets ORDER BY category = 'Others', category", String.class);
        List<String> header = new ArrayList<>();
        header.add("Agent ↓ / Ours →");
        header.addAll(categories);
        header.add("Agreement");
        List<List<String>> rows = new ArrayList<>();
        for (String agent : categories) {
            List<String> row = new ArrayList<>();
            row.add("**" + agent + "**");
            long total = 0;
            long same = 0;
            for (String ours : categories) {
                long n = num(jdbc.queryForObject(
                        "SELECT COUNT(*) FROM ticket_topics WHERE category = ? AND topic_category = ?",
                        Long.class, agent, ours));
                total += n;
                if (agent.equals(ours)) {
                    same = n;
                }
                row.add(n == 0 ? "·" : agent.equals(ours) ? "**" + fmt(n) + "**" : fmt(n));
            }
            row.add(pct(same, total));
            rows.add(row);
        }
        table(md, header, rows);
        md.append("\nEverything off the diagonal sits in the *Others* row.\n\n");

        md.append("What the %s *Others › Unclassified* tickets actually are:\n\n".formatted(fmt(num(jdbc.queryForObject(
                "SELECT COUNT(*) FROM tickets WHERE subcategory = 'Unclassified'", Long.class)))));
        List<Map<String, Object>> unclassified = jdbc.queryForList("""
                SELECT topic_category || ' › ' || topic_subcategory AS topic, COUNT(*) AS tickets
                FROM ticket_topics WHERE subcategory = 'Unclassified'
                GROUP BY topic ORDER BY tickets DESC LIMIT 10
                """);
        long total = unclassified.stream().mapToLong(r -> num(r.get("tickets"))).sum();
        table(md, List.of("Our topic", "Tickets"), unclassified.stream()
                .map(r -> List.of(r.get("topic").toString(), fmt(num(r.get("tickets"))))).toList());
        md.append("\n(top 10 shown, %s tickets)\n\n".formatted(fmt(total)));
    }

    private void whereItHappens(StringBuilder md) {
        md.append("## 3. Is the mislabelling concentrated anywhere?\n\n")
                .append("Share of real complaints filed as Unclassified, by dimension (min – max across values). ")
                .append("A process problem in one team or channel would show up as one outlier.\n\n");
        List<List<String>> rows = new ArrayList<>();
        for (String dim : List.of("channel", "region", "priority", "segment", "status", "topic_category")) {
            Map<String, Object> r = jdbc.queryForMap("""
                    WITH rates AS (
                        SELECT %1$s AS value, 100.0 * AVG(%2$s) AS rate
                        FROM ticket_topics
                        WHERE topic_category <> 'Others'
                        GROUP BY %1$s
                    )
                    SELECT MIN(rate) AS lo, MAX(rate) AS hi,
                           (SELECT value FROM rates ORDER BY rate DESC LIMIT 1) AS worst
                    FROM rates
                    """.formatted(dim, DUMPED));
            rows.add(List.of(dim.equals("topic_category") ? "our topic" : dim,
                    String.format(Locale.ROOT, "%.1f%% – %.1f%%", num2(r.get("lo")), num2(r.get("hi"))),
                    String.valueOf(r.get("worst"))));
        }
        table(md, List.of("Dimension", "Range", "Highest"), rows);
        md.append("\nThe spread is narrow everywhere, so this looks like a uniform labelling habit — ")
                .append("Unclassified used as a default when the agent is unsure or rushed — rather than one team. ")
                .append("The data has no agent ID, so it cannot be traced further.\n\n");
    }

    private void impact(StringBuilder md) {
        md.append("## 4. What it does to the numbers\n\n");
        List<Map<String, Object>> rows = jdbc.queryForList("""
                SELECT c.category,
                       (SELECT COUNT(*) FROM ticket_topics WHERE category = c.category) AS agent,
                       (SELECT COUNT(*) FROM ticket_topics WHERE topic_category = c.category) AS ours
                FROM (SELECT DISTINCT category FROM tickets) c
                ORDER BY ours DESC
                """);
        table(md, List.of("Category", "Agent label", "Our topic", "Difference"), rows.stream()
                .map(r -> {
                    long agent = num(r.get("agent"));
                    long ours = num(r.get("ours"));
                    return List.of(r.get("category").toString(), fmt(agent), fmt(ours),
                            String.format(Locale.ROOT, "%+.1f%%", 100.0 * (ours - agent) / agent));
                })
                .toList());
        Map<String, Object> pcna = jdbc.queryForMap("""
                SELECT SUM(subcategory = 'Package charged but not active') AS agent,
                       SUM(topic_subcategory = 'Package charged but not active') AS ours
                FROM ticket_topics
                WHERE week_start >= (SELECT date(MAX(week_start), '-21 days') FROM tickets)
                """);
        md.append("\nExample: *Package charged but not active* in the last 4 weeks — %s tickets by agent label, "
                        .formatted(fmt(num(pcna.get("agent")))))
                .append("%s by note content. The weekly brief uses our topic.\n\n".formatted(fmt(num(pcna.get("ours")))));
    }

    private void limitations(StringBuilder md) {
        md.append("## 5. Limitations\n\n")
                .append("- One note per ticket, one topic per note. A note mentioning two problems gets the dominant one.\n")
                .append("- The review is one person's judgment. A second reviewer and an agreement score ")
                .append("(Cohen's κ) would be the next step before using this for agent coaching.\n")
                .append("- With 91 distinct texts every label can be reviewed. Real notes are mostly unique; see the ")
                .append("README for how this would change at scale.\n");
    }

    // --- formatting helpers ---

    private static void table(StringBuilder md, List<String> header, List<List<String>> rows) {
        md.append("| ").append(String.join(" | ", header)).append(" |\n|");
        header.forEach(h -> md.append("---|"));
        md.append('\n');
        for (List<String> row : rows) {
            md.append("| ").append(String.join(" | ", row)).append(" |\n");
        }
    }

    private static long num(Object value) {
        return value == null ? 0 : ((Number) value).longValue();
    }

    private static double num2(Object value) {
        return value == null ? 0 : ((Number) value).doubleValue();
    }

    private static String fmt(long n) {
        return String.format(Locale.ROOT, "%,d", n);
    }

    private static String pct(long part, long whole) {
        return whole == 0 ? "n/a" : String.format(Locale.ROOT, "%.1f%%", 100.0 * part / whole);
    }
}
